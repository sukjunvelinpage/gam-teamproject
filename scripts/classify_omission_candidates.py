def load_candidates() -> pd.DataFrame:
    df = pd.read_csv(TWEETS_PATH, low_memory=False, dtype={"id": str})
    cand = df[df["additional_tone_scope"] == "candidate_eligible"]
    omission = cand[cand["source_group"] == "screened_437"].assign(origin="omission59")
    themed = cand[cand["additional_themes"].fillna("").str.contains(SCOPE_THEME_PATTERN, case=False)]
    themed = themed.assign(origin="theme79")
    out = pd.concat([omission, themed]).drop_duplicates("raw_row")
    assert len(omission) == 59 and len(themed) == 79 and len(out) == 138, "후보 구성이 바뀌었습니다"
    return out


def main():
    cand = load_candidates()
    missing = set(cand["raw_row"]) - set(DECISIONS)
    extra = set(DECISIONS) - set(cand["raw_row"])
    assert not missing and not extra, f"판정 누락 {sorted(missing)} / 초과 {sorted(extra)}"

    cand["subtype"] = cand["raw_row"].map(lambda r: DECISIONS[r][0])
    cand["trade_topic"] = cand["raw_row"].map(lambda r: DECISIONS[r][1])
    cand["reason_ko"] = cand["raw_row"].map(lambda r: DECISIONS[r][2])
    cand["signal"] = cand["subtype"].map(
        lambda s: "Positive" if s.startswith("POS") else ("Negative" if s.startswith("NEG") else "Noise")
    )
    # 거래일: 기존 1,246건과 같이 저장 시각 기준 후보를 쓴다 (시각 충돌 3건도 저장 시각 기준)
    cand["mapped_trading_date"] = cand["stored_time_trading_date_candidate"]
    cols = ["raw_row", "audit_key", "date_utc", "isRetweet", "origin", "additional_themes", "text",
            "signal", "subtype", "trade_topic", "reason_ko", "mapped_trading_date", "time_assignment_status"]
    out = cand[cols].sort_values("raw_row")
    out.to_csv(OUT_PATH, index=False, encoding="utf-8-sig")
    print(f"저장: {OUT_PATH} ({len(out)}건)")
    print(out.groupby(["signal", "subtype"]).size().to_string())
    print("trade_topic=1:", int(out["trade_topic"].sum()), "/ 거래일 없음:", int(out["mapped_trading_date"].isna().sum()))


if __name__ == "__main__":
    main()
